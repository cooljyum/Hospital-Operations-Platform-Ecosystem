-- =====================================================================
-- V2: 표시용 식별자(synthetic_patient_no) 분리
-- =====================================================================
ALTER TABLE PATIENT ADD synthetic_patient_no VARCHAR2(32) NULL;

CREATE TABLE PATIENT_DISPLAY_ID (
    display_id_seq          NUMBER(19)   GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id                NUMBER(19)   NOT NULL,
    synthetic_patient_no       VARCHAR2(32) NOT NULL,
    issued_at                    TIMESTAMP    DEFAULT SYSTIMESTAMP NOT NULL,
    is_active                     NUMBER(1)    DEFAULT 1 NOT NULL,
    CONSTRAINT uq_patient_display_id_no UNIQUE (synthetic_patient_no),
    CONSTRAINT fk_patient_display_id_patient FOREIGN KEY (patient_id) REFERENCES PATIENT (patient_id),
    CONSTRAINT chk_patient_display_id_active CHECK (is_active IN (0, 1))
);
-- MySQL BOOLEAN/TINYINT(1) -> Oracle 19c는 네이티브 BOOLEAN 컬럼이 없어(23c부터 지원)
-- NUMBER(1) + CHECK 제약으로 대체하는 것이 19c 호환 표준 패턴이다.

-- MySQL 원본은 "행이 없는 시점"을 이용해 즉시 NOT NULL+UNIQUE로 MODIFY했지만,
-- Oracle 분기는 새 스키마이므로 처음부터 NOT NULL로 정의하고 UNIQUE만 추가한다.
ALTER TABLE PATIENT MODIFY synthetic_patient_no VARCHAR2(32) NOT NULL;
ALTER TABLE PATIENT ADD CONSTRAINT uq_patient_synthetic_no UNIQUE (synthetic_patient_no);


-- =====================================================================
-- V3: LAB_RESULT/PRESCRIPTION 자연키 보강 (생성 컬럼 + 유니크)
-- =====================================================================
-- MySQL은 STORED 생성 컬럼(디스크에 실제 저장)을 쓰지만, Oracle 19c는 STORED를
-- 지원하지 않고 VIRTUAL(조회 시 계산, 인덱스는 가능)만 지원한다. 유니크
-- 제약/인덱스는 VIRTUAL 컬럼에도 그대로 걸 수 있어 기능적 동등성은 유지된다
-- (디스크 저장 여부만 다르고, "NULL끼리는 유니크 충돌 안 남" 문제를 고정
-- 센티널로 우회하는 목적은 동일하게 달성).
ALTER TABLE LAB_RESULT
    ADD result_value_key VARCHAR2(255)
        GENERATED ALWAYS AS (COALESCE(result_value, '')) VIRTUAL NOT NULL;

ALTER TABLE LAB_RESULT
    ADD CONSTRAINT uq_lab_result_natural UNIQUE (visit_id, code, observed_at, result_value_key);

ALTER TABLE PRESCRIPTION
    ADD stopped_at_key TIMESTAMP
        GENERATED ALWAYS AS (COALESCE(stopped_at, TIMESTAMP '9999-12-31 23:59:59')) VIRTUAL NOT NULL;

ALTER TABLE PRESCRIPTION
    ADD CONSTRAINT uq_prescription_natural UNIQUE (visit_id, medication_code, started_at, stopped_at_key);

-- 참고: MySQL 원본은 "새 인덱스 추가 -> 기존 인덱스 DROP -> RENAME INDEX" 3단계였다
-- (FK가 항상 인덱스를 갖고 있어야 하므로). Oracle 분기는 처음부터 최종 제약만
-- 한 번에 걸므로 이 절차가 필요 없다. 만약 기존 Oracle 스키마에 이미 구버전
-- 제약이 있고 이후 이 형태로 바꿔야 한다면 Oracle 문법은 다음과 같이 다르다:
--   ALTER INDEX uq_lab_result_natural_old RENAME TO uq_lab_result_natural;  (MySQL RENAME INDEX 대응)
--   DROP INDEX uq_lab_result_natural_old;                                   (MySQL DROP INDEX table.idx 대응 — Oracle은 스키마 레벨 오브젝트라 테이블명 없이 인덱스명만 씀)


-- =====================================================================
-- V4: 자유 텍스트 설명 컬럼 폭 확장
-- =====================================================================
-- Oracle 분기는 V1에서 이미 최종 폭(500/600)으로 정의했으므로 이 섹션은 변경
-- 사항 없음(신규 스키마라 중간 이력을 재현할 필요가 없기 때문). MySQL처럼
-- 기존 운영 스키마에 사후 반영해야 한다면 Oracle 문법은:
--   ALTER TABLE PRESCRIPTION MODIFY medication_description VARCHAR2(600);
--   ALTER TABLE PRESCRIPTION MODIFY reason_description VARCHAR2(500);
--   ALTER TABLE VISIT MODIFY encounter_description VARCHAR2(500);
--   ALTER TABLE VISIT MODIFY reason_description VARCHAR2(500);
--   ALTER TABLE LAB_RESULT MODIFY description VARCHAR2(500);
-- (MySQL은 컬럼명 앞에 MODIFY COLUMN, Oracle은 MODIFY만 쓰고 컬럼 타입을
-- 다시 명시하는 점은 동일하다 — 큰 차이는 아니지만 "COLUMN" 키워드 유무가 다르다.)


-- =====================================================================
-- V5: Spring Batch 메타데이터 + FHIR 동기화 캐시/워터마크
-- =====================================================================
-- 중요: BATCH_JOB_INSTANCE 등 8개 Spring Batch 메타데이터 테이블은 손으로
-- 번역하지 않는다. spring-batch-core-5.2.6.jar 안에
--   org/springframework/batch/core/schema-oracle.sql
-- 이 Oracle 전용 공식 스키마로 이미 포함되어 있다(BATCH_STEP_EXECUTION_SEQ 등
-- MySQL의 "유니크 제약을 건 1행짜리 카운터 테이블" 패턴 대신 Oracle 네이티브
-- SEQUENCE 오브젝트를 쓰는 등 구조 자체가 다르다). 이 파일을 직접 짜면
-- JobRepository 내부 SQL과 컬럼/제약이 미묘하게 어긋나 배치가 깨질 위험이
-- 있으므로, Oracle 분기 착수 시 반드시 그 jar 안의 원본 파일을 그대로
-- 사용한다(V5 원본 MySQL 마이그레이션 주석도 "임의로 손으로 짜지 않고 실제
-- 배포되는 스키마 원본을 사용"이라고 명시한 원칙과 동일한 이유).
--
-- 아래는 이 프로젝트가 직접 설계한 나머지 두 테이블(SYNC_WATERMARK,
-- FHIR_RESOURCE_CACHE)만 번역한다.

CREATE TABLE SYNC_WATERMARK (
    resource_type          VARCHAR2(30) PRIMARY KEY,
    last_synced_at           TIMESTAMP    DEFAULT TIMESTAMP '1970-01-01 00:00:00' NOT NULL,
    updated_at                 TIMESTAMP    DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE OR REPLACE TRIGGER trg_sync_watermark_updated_at
    BEFORE UPDATE ON SYNC_WATERMARK
    FOR EACH ROW
BEGIN
    :NEW.updated_at := SYSTIMESTAMP;
END;
/

-- MySQL LONGTEXT -> Oracle CLOB.
