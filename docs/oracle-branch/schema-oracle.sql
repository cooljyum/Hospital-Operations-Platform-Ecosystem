-- =====================================================================
-- Hospital FHIR Ops Lab — Oracle 19c 분기 참고 DDL
-- =====================================================================
-- 이 파일은 MySQL 8.x 정본 스키마(app/src/main/resources/db/migration/V1~V16)를
-- Oracle SQL 방언으로 번역한 참고 DDL이다. Flyway 마이그레이션으로 앱에 실제
-- 연결되어 있지는 않다(이 프로젝트의 DB는 MySQL 8.x 단일 구현이 정본이며, 이
-- 문서는 deliverable.md §2가 예고한 "별도 분기 문서"다).
--
-- 각 섹션은 대응하는 MySQL 마이그레이션 파일 번호(Vn)를 그대로 따서 표시했다 —
-- 다시 확인할 때 원본과 1:1로 대조하기 쉽게 하기 위함이다. Oracle에서 자연스러운
-- 형태로 재구성하지 않고, "MySQL DDL을 Oracle 방언으로 옮기면 무엇이 달라지는가"를
-- 그대로 드러내는 것을 우선했다(예: V3의 STORED 생성 컬럼 → Oracle은 VIRTUAL만
-- 지원, V5의 RENAME INDEX 문법 차이 등). 상세 문법 차이표는 같은 디렉터리의
-- mysql-oracle-dialect-diff.md 참고.
--
-- 실기동 검증: gvenzl/oracle-free:23-slim(커뮤니티 무료 이미지, Oracle Database
-- Free 23ai 기반) 컨테이너에 이 파일 전체를 sqlplus로 실제 적용해 전 구문이
-- 에러 없이 실행됨을 확인했다(2026-07-20). 상세는 README.md "실기동 결과" 참고 —
-- 라이선스가 필요한 진짜 Oracle 19c 이미지(container-registry.oracle.com, OTN
-- 계정 인증 필요)는 이 자동화 환경에서 받을 수 없어 미검증이며, 23ai와 19c는
-- 같은 SQL/PLSQL 방언 계열이라 문법 차이가 극히 적지만 100% 동일은 아니다.
-- =====================================================================


-- =====================================================================
-- V1: 레거시 HIS 핵심 스키마 (PATIENT / VISIT / LAB_RESULT / PRESCRIPTION)
-- =====================================================================
-- MySQL BIGINT AUTO_INCREMENT -> Oracle NUMBER(19) GENERATED BY DEFAULT AS
-- IDENTITY (12c+ 네이티브 identity column, 19c에서 지원). MySQL DATETIME ->
-- Oracle TIMESTAMP. ENGINE/CHARSET/COLLATE 절은 Oracle에 대응 개념이 없어
-- 제거(문자셋은 데이터베이스 생성 시 AL32UTF8로 지정하는 것으로 대체).
--
-- MySQL의 "DATETIME ... ON UPDATE CURRENT_TIMESTAMP"는 Oracle에 직접 대응
-- 문법이 없다 — Oracle은 컬럼 자동 갱신을 트리거로 구현해야 한다. 4개 테이블
-- 전부 같은 패턴이므로 PATIENT 하나에만 대표로 트리거를 달고 나머지 3개는
-- 동일 패턴이라는 점만 주석으로 남긴다(실제 분기 착수 시 4개 모두 동일하게
-- 복제하면 된다).

CREATE TABLE PATIENT (
    patient_id             NUMBER(19)    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_patient_uuid    VARCHAR2(64)  NOT NULL,
    birth_date              DATE          NULL,
    death_date              DATE          NULL,
    prefix                  VARCHAR2(20)  NULL,
    first_name              VARCHAR2(100) NULL,
    middle_name             VARCHAR2(100) NULL,
    last_name               VARCHAR2(100) NULL,
    suffix                  VARCHAR2(20)  NULL,
    maiden_name             VARCHAR2(100) NULL,
    marital_status          VARCHAR2(10)  NULL,
    race                    VARCHAR2(50)  NULL,
    ethnicity               VARCHAR2(50)  NULL,
    gender                  VARCHAR2(10)  NULL,
    birthplace              VARCHAR2(255) NULL,
    address                 VARCHAR2(255) NULL,
    city                    VARCHAR2(100) NULL,
    state                   VARCHAR2(100) NULL,
    county                  VARCHAR2(100) NULL,
    zip                     VARCHAR2(20)  NULL,
    created_at              TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at              TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT uq_patient_source_uuid UNIQUE (source_patient_uuid)
);

-- MySQL "ON UPDATE CURRENT_TIMESTAMP" 대체 트리거 (PATIENT 대표 예시).
CREATE OR REPLACE TRIGGER trg_patient_updated_at
    BEFORE UPDATE ON PATIENT
    FOR EACH ROW
BEGIN
    :NEW.updated_at := SYSTIMESTAMP;
END;
/

